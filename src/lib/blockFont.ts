export const FONT_HEIGHT = 7

/** Characters the font can draw (others are skipped). */
export function supported(ch: string) {
  return ch.toUpperCase() in G
}

/** A filled/empty bitmap for `text`, with one empty column between letters. */
export function textBitmap(text: string, scale: 1 | 2 = 1): { width: number; height: number; on: boolean[][] } {
  const glyphs = [...text.toUpperCase()].map((c) => G[c]).filter(Boolean)
  const baseW = glyphs.reduce((w, g, i) => w + g[0].length + (i ? 1 : 0), 0)
  const rows: boolean[][] = Array.from({ length: FONT_HEIGHT }, () => new Array(baseW).fill(false))
  let x = 0
  glyphs.forEach((g, i) => {
    if (i) x += 1
    for (let r = 0; r < FONT_HEIGHT; r++) for (let c = 0; c < g[r].length; c++) if (g[r][c] === '#') rows[r][x + c] = true
    x += g[0].length
  })
  if (scale === 1) return { width: baseW, height: FONT_HEIGHT, on: rows }
  const on = Array.from({ length: FONT_HEIGHT * 2 }, (_, r) =>
    Array.from({ length: baseW * 2 }, (_, c) => rows[r >> 1][c >> 1]),
  )
  return { width: baseW * 2, height: FONT_HEIGHT * 2, on }
}
